def run_bugfix_pipeline(bug_report, target_file, target_function):

    print("=" * 60)
    print("🚀 AUTONOMOUS BUG FIXING PIPELINE")
    print("=" * 60)

    # ------------------------------------------------
    # 1. Read repository
    # ------------------------------------------------
    repository = read_repository("bugfix_demo")
    repository_context = create_repository_context(repository)

    print("\n🔍 STEP 1: BUG ANALYSIS")

    analysis = bug_analyzer(
        bug_report,
        repository_context
    )

    print(analysis)

    # ------------------------------------------------
    # 2. Generate fix
    # ------------------------------------------------
    print("\n🔧 STEP 2: FIX GENERATION")

    fix = fix_generator(
        bug_report,
        repository_context,
        analysis
    )

    print(fix)

    # ------------------------------------------------
    # 3. Extract corrected function
    # ------------------------------------------------
    corrected_function = extract_code(fix)

    if corrected_function is None:
        print("\n❌ Could not extract corrected code.")
        return

    # ------------------------------------------------
    # 4. Test fix
    # ------------------------------------------------
    print("\n🧪 STEP 3: TESTING")

    test_result = test_fix(
        target_file,
        corrected_function
    )

    print(test_result.stdout)

    # ------------------------------------------------
    # 5. Review
    # ------------------------------------------------
    print("\n🔎 STEP 4: REVIEW")

    review = reviewer_agent(
        bug_report,
        analysis,
        fix,
        test_result.stdout
    )

    print(review)

    print("\n" + "=" * 60)
    print("✅ PIPELINE COMPLETE")
    print("=" * 60)

    return {
        "analysis": analysis,
        "fix": fix,
        "test_results": test_result.stdout,
        "review": review
    }

