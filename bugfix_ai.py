def run_from_ui(bug_report):

    if not bug_report.strip():
        return (
            "Please enter a bug report.",
            "",
            "",
            ""
        )

    # Identify target module
    if "average" in bug_report.lower() or "empty list" in bug_report.lower():
        target_file = "bugfix_demo/app/calculator.py"
        target_function = "calculate_average"

    elif "email" in bug_report.lower():
        target_file = "bugfix_demo/app/user_service.py"
        target_function = "get_user_email"

    elif "discount" in bug_report.lower() or "₹1000" in bug_report or "1000" in bug_report:
        target_file = "bugfix_demo/app/order_service.py"
        target_function = "calculate_discount"

    else:
        return (
            "❌ Could not identify the bug type.",
            "",
            "",
            "Please describe an average, discount, or missing-email bug."
        )

    # Run complete pipeline
    result = run_bugfix_pipeline(
        bug_report,
        target_file,
        target_function
    )

    return (
        result["analysis"],
        result["fix"],
        result["test_results"],
        result["review"]
    )


