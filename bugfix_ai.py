def read_repository(repo_path):
    repository = {}

    for root, dirs, files in os.walk(repo_path):

        # Ignore test files for now
        if "tests" in root:
            continue

        for file in files:
            if file.endswith(".py"):
                file_path = os.path.join(root, file)

                with open(file_path, "r") as f:
                    repository[file_path] = f.read()

    return repository


